(function () {
	'use strict';

	var PREFIX     = '[fc_swiper]';
	var MAX_TRIES  = 100;   // 100 x 100ms = 10s before giving up on the libraries
	var WAIT_DELAY = 100;
	var tries      = 0;

	var VALID_EFFECTS = ['slide', 'fade', 'cube', 'flip', 'coverflow', 'cards', 'creative'];
