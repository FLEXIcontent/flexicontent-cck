// Decode HTML entities until the string is stable
if ( !function_exists('fc_swiper_decode_until_stable') )
{
	function fc_swiper_decode_until_stable($s)
	{
		$prev = '';
		$cur  = (string) $s;
		for ($i = 0; $i < 4 && $cur !== $prev; $i++)
		{
			$prev = $cur;
			$cur  = html_entity_decode($cur, ENT_QUOTES, 'UTF-8');
		}
		return $cur;
	}
}

