		var gridRows = intAttr(container, 'data-grid-rows', 1) || 1;

		if (gridRows > 1 && GRID_EFFECTS.indexOf(fx) === -1) {
			logWarn(label(container) + ': effect "' + fx + '" does not support a multi-row grid, rows forced to 1');
			gridRows = 1;
