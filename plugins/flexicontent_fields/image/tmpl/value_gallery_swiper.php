	function fc_swiper_yn($v, $default = 0)
	{
		$v = $v === null ? $default : $v;
		if (is_bool($v)) return (int) $v;
		if (is_string($v))
		{
			if ($v === 'true'  || $v === '1') return 1;
			if ($v === 'false' || $v === '0') return 0;
		}
		return (int) $v;
	}
}

